-- ============================================================
-- 01_auditoria.sql  (Auditoría: tablas audi_users y audi_vinculations y sus triggers)
-- ============================================================
-- Auditoría de public.users: guarda el estado de cada fila antes (OLD) y después (NEW) de un INSERT, UPDATE o DELETE.
-- Se omiten password, reset_token y reset_token_expiry: nunca se guardan secretos en la auditoría.
CREATE TABLE IF NOT EXISTS public.audi_users (
    audit_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    operation  VARCHAR(10)  NOT NULL,
    state      CHAR(3)      NOT NULL,
    changed_by VARCHAR(100) NOT NULL DEFAULT current_user,
    changed_at TIMESTAMP(6) NOT NULL DEFAULT now(),
    must_change_password     BOOLEAN,
    company_id               BIGINT,
    role_id                  BIGINT,
    user_id                  BIGINT,
    email                    VARCHAR(100),
    name                     VARCHAR(100),
    CONSTRAINT pk_audi_users PRIMARY KEY (audit_id),
    CONSTRAINT ck_audi_users_operation CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    CONSTRAINT ck_audi_users_state CHECK (state IN ('OLD', 'NEW'))
);

CREATE INDEX IF NOT EXISTS idx_audi_users_user_id ON public.audi_users (user_id);
CREATE INDEX IF NOT EXISTS idx_audi_users_changed_at ON public.audi_users (changed_at);

-- Auditoría de public.vinculations: guarda el estado de cada fila antes (OLD) y después (NEW) de un INSERT, UPDATE o DELETE.
CREATE TABLE IF NOT EXISTS public.audi_vinculations (
    audit_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    operation  VARCHAR(10)  NOT NULL,
    state      CHAR(3)      NOT NULL,
    changed_by VARCHAR(100) NOT NULL DEFAULT current_user,
    changed_at TIMESTAMP(6) NOT NULL DEFAULT now(),
    device_id                BIGINT,
    driver_id                BIGINT,
    linked_at                TIMESTAMP(6),
    vehicle_id               BIGINT,
    vinculation_id           BIGINT,
    CONSTRAINT pk_audi_vinculations PRIMARY KEY (audit_id),
    CONSTRAINT ck_audi_vinculations_operation CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    CONSTRAINT ck_audi_vinculations_state CHECK (state IN ('OLD', 'NEW'))
);

CREATE INDEX IF NOT EXISTS idx_audi_vinculations_vinculation_id ON public.audi_vinculations (vinculation_id);
CREATE INDEX IF NOT EXISTS idx_audi_vinculations_changed_at ON public.audi_vinculations (changed_at);

-- Trigger de auditoría de public.users (guarda en public.audi_users).
CREATE OR REPLACE FUNCTION public.fn_audi_users() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.audi_users (operation, state, must_change_password, company_id, role_id, user_id, email, name)
        VALUES (TG_OP, 'NEW', NEW.must_change_password, NEW.company_id, NEW.role_id, NEW.user_id, NEW.email, NEW.name);
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO public.audi_users (operation, state, must_change_password, company_id, role_id, user_id, email, name)
        VALUES (TG_OP, 'OLD', OLD.must_change_password, OLD.company_id, OLD.role_id, OLD.user_id, OLD.email, OLD.name);
        INSERT INTO public.audi_users (operation, state, must_change_password, company_id, role_id, user_id, email, name)
        VALUES (TG_OP, 'NEW', NEW.must_change_password, NEW.company_id, NEW.role_id, NEW.user_id, NEW.email, NEW.name);
        RETURN NEW;
    ELSE
        INSERT INTO public.audi_users (operation, state, must_change_password, company_id, role_id, user_id, email, name)
        VALUES (TG_OP, 'OLD', OLD.must_change_password, OLD.company_id, OLD.role_id, OLD.user_id, OLD.email, OLD.name);
        RETURN OLD;
    END IF;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audi_users ON public.users;
CREATE TRIGGER trg_audi_users AFTER INSERT OR UPDATE OR DELETE ON public.users
    FOR EACH ROW EXECUTE FUNCTION public.fn_audi_users();

