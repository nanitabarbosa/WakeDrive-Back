-- Migración automática del esquema antiguo (tablas en singular, PK "id", tipos como texto)
-- al esquema actual (tablas en plural, PK "<entidad>_id", catálogos brands/vehicle_types/event_types).
-- Spring la ejecuta ANTES de que Hibernate cree/actualice tablas (ver application.properties).
-- Es idempotente: si la base ya tiene el esquema nuevo, o está vacía, no hace nada.
-- Cada bloque termina con ";;" (separador configurado en spring.sql.init.separator).

DO $$
DECLARE
    pair text[];
    renames text[][] := ARRAY[
        ARRAY['access_request', 'access_requests', 'access_request_id'],
        ARRAY['alert',          'alerts',          'alert_id'],
        ARRAY['city',           'cities',          'city_id'],
        ARRAY['company',        'companies',       'company_id'],
        ARRAY['device',         'devices',         'device_id'],
        ARRAY['driver',         'drivers',         'driver_id'],
        ARRAY['notification',   'notifications',   'notification_id'],
        ARRAY['vehicle',        'vehicles',        'vehicle_id'],
        ARRAY['vinculation',    'vinculations',    'vinculation_id']
    ];
BEGIN
    -- 1) Tablas renombradas + PK id -> <entidad>_id
    FOREACH pair SLICE 1 IN ARRAY renames LOOP
        IF to_regclass('public.' || pair[1]) IS NOT NULL AND to_regclass('public.' || pair[2]) IS NULL THEN
            EXECUTE format('ALTER TABLE public.%I RENAME TO %I', pair[1], pair[2]);
            EXECUTE format('ALTER TABLE public.%I RENAME COLUMN id TO %I', pair[2], pair[3]);
        END IF;
    END LOOP;

    -- 2) Tablas que conservan el nombre pero cambian la PK
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'roles' AND column_name = 'id') THEN
        ALTER TABLE public.roles RENAME COLUMN id TO role_id;
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'id') THEN
        ALTER TABLE public.users RENAME COLUMN id TO user_id;
    END IF;

    -- 3) vehicles.brand (texto) -> brands + vehicles.brand_id
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'vehicles' AND column_name = 'brand') THEN
        CREATE TABLE IF NOT EXISTS public.brands (
            brand_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name varchar(255) NOT NULL UNIQUE
        );
        INSERT INTO public.brands (name) SELECT DISTINCT brand FROM public.vehicles ON CONFLICT (name) DO NOTHING;
        ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS brand_id bigint;
        UPDATE public.vehicles v SET brand_id = b.brand_id FROM public.brands b WHERE b.name = v.brand;
        ALTER TABLE public.vehicles ALTER COLUMN brand_id SET NOT NULL;
        ALTER TABLE public.vehicles DROP COLUMN brand;
    END IF;

    -- 4) vehicles.type (texto) -> vehicle_types + vehicles.vehicle_type_id
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'vehicles' AND column_name = 'type') THEN
        CREATE TABLE IF NOT EXISTS public.vehicle_types (
            vehicle_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name varchar(255) NOT NULL UNIQUE
        );
        INSERT INTO public.vehicle_types (name) SELECT DISTINCT type FROM public.vehicles ON CONFLICT (name) DO NOTHING;
        ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS vehicle_type_id bigint;
        UPDATE public.vehicles v SET vehicle_type_id = t.vehicle_type_id FROM public.vehicle_types t WHERE t.name = v.type;
        ALTER TABLE public.vehicles ALTER COLUMN vehicle_type_id SET NOT NULL;
        ALTER TABLE public.vehicles DROP COLUMN type;
    END IF;

    -- 5) alerts.type (texto) -> event_types + alerts.event_type_id
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'alerts' AND column_name = 'type') THEN
        CREATE TABLE IF NOT EXISTS public.event_types (
            event_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name varchar(255) NOT NULL UNIQUE
        );
        INSERT INTO public.event_types (name) SELECT DISTINCT type FROM public.alerts ON CONFLICT (name) DO NOTHING;
        ALTER TABLE public.alerts ADD COLUMN IF NOT EXISTS event_type_id bigint;
        UPDATE public.alerts a SET event_type_id = e.event_type_id FROM public.event_types e WHERE e.name = a.type;
        ALTER TABLE public.alerts ALTER COLUMN event_type_id SET NOT NULL;
        ALTER TABLE public.alerts DROP COLUMN type;
    END IF;
END
$$;;
